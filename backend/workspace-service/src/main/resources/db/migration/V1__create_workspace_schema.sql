-- Workspace, membership and invitation tables.
-- User ids come from the auth service (a separate database), so they are plain
-- strings without foreign keys, like documents.author_id in the document service.

CREATE TABLE workspaces (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    visibility VARCHAR(10) NOT NULL DEFAULT 'PRIVATE',
    owner_id VARCHAR(120) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_workspaces_visibility CHECK (visibility IN ('PRIVATE', 'PUBLIC'))
);

CREATE INDEX idx_workspaces_owner ON workspaces (owner_id);

CREATE TABLE workspace_members (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id BIGINT NOT NULL,
    user_id VARCHAR(120) NOT NULL,
    role VARCHAR(10) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_workspace_members_workspace
        FOREIGN KEY (workspace_id) REFERENCES workspaces (id) ON DELETE CASCADE,
    CONSTRAINT uq_workspace_members_workspace_user UNIQUE (workspace_id, user_id),
    CONSTRAINT ck_workspace_members_role CHECK (role IN ('OWNER', 'EDITOR', 'VIEWER'))
);

CREATE INDEX idx_workspace_members_user ON workspace_members (user_id);

CREATE TABLE workspace_invitations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id BIGINT NOT NULL,
    email VARCHAR(254) NOT NULL,
    -- OWNER cannot be granted by invitation.
    role VARCHAR(10) NOT NULL,
    -- SHA-256 hex digest of the invitation token; the raw token is never stored.
    token_hash VARCHAR(64) NOT NULL,
    status VARCHAR(10) NOT NULL DEFAULT 'PENDING',
    invited_by VARCHAR(120) NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_workspace_invitations_workspace
        FOREIGN KEY (workspace_id) REFERENCES workspaces (id) ON DELETE CASCADE,
    CONSTRAINT uq_workspace_invitations_token UNIQUE (token_hash),
    CONSTRAINT ck_workspace_invitations_role CHECK (role IN ('EDITOR', 'VIEWER')),
    CONSTRAINT ck_workspace_invitations_status
        CHECK (status IN ('PENDING', 'ACCEPTED', 'REVOKED', 'EXPIRED'))
);

-- "One pending invitation per workspace and email" is enforced by the service
-- layer: a partial unique index is not portable to the H2 database used in tests.
CREATE INDEX idx_workspace_invitations_workspace_email
    ON workspace_invitations (workspace_id, email);
