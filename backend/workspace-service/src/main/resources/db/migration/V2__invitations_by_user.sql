-- MS-03: invitations target a user id (resolved through the auth service) instead of an email
-- address and token, and every workspace owner is guaranteed an OWNER membership.

-- Workspaces created through the API already have an OWNER membership; this repairs any that do
-- not, and never changes an existing membership of another user.
INSERT INTO workspace_members (workspace_id, user_id, role, created_at, updated_at)
SELECT w.id, w.owner_id, 'OWNER', CURRENT_TIMESTAMP, CURRENT_TIMESTAMP
FROM workspaces w
WHERE NOT EXISTS (
    SELECT 1 FROM workspace_members m WHERE m.workspace_id = w.id AND m.user_id = w.owner_id);

UPDATE workspace_members
SET role = 'OWNER'
WHERE role <> 'OWNER'
  AND EXISTS (
    SELECT 1 FROM workspaces w
    WHERE w.id = workspace_members.workspace_id AND w.owner_id = workspace_members.user_id);

-- The V1 table had no endpoints, so it holds no real data, and email-only rows cannot be mapped to
-- user ids. Replace it.
DROP TABLE workspace_invitations;

CREATE TABLE workspace_invitations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id BIGINT NOT NULL,
    -- Plain string without a foreign key: users live in the auth service's database.
    invited_user_id VARCHAR(120) NOT NULL,
    -- What the inviter typed, for display only; null when invited by username.
    invited_email VARCHAR(254),
    -- OWNER cannot be granted by invitation.
    role VARCHAR(10) NOT NULL,
    status VARCHAR(10) NOT NULL DEFAULT 'PENDING',
    invited_by VARCHAR(120) NOT NULL,
    -- TRUE while PENDING, NULL once closed. NULLs are distinct in a unique constraint, so this
    -- allows one pending invitation per workspace and user in PostgreSQL and H2 alike.
    pending_marker BOOLEAN,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_workspace_invitations_workspace
        FOREIGN KEY (workspace_id) REFERENCES workspaces (id) ON DELETE CASCADE,
    CONSTRAINT uq_workspace_invitations_pending
        UNIQUE (workspace_id, invited_user_id, pending_marker),
    CONSTRAINT ck_workspace_invitations_role CHECK (role IN ('EDITOR', 'VIEWER')),
    CONSTRAINT ck_workspace_invitations_status
        CHECK (status IN ('PENDING', 'ACCEPTED', 'DECLINED', 'REVOKED')),
    CONSTRAINT ck_workspace_invitations_pending_marker
        CHECK ((status = 'PENDING') = (pending_marker IS NOT NULL))
);

CREATE INDEX idx_workspace_invitations_user_status
    ON workspace_invitations (invited_user_id, status);
CREATE INDEX idx_workspace_invitations_workspace_status
    ON workspace_invitations (workspace_id, status);
